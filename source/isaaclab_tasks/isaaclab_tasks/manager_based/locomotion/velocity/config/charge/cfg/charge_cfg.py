import isaaclab.sim as sim_utils  # 模擬工具：物理引擎、USD文件加載
from isaaclab.actuators import ImplicitActuatorCfg  # 執行器配置：定義馬達/輪子如何驅動
from isaaclab.assets.articulation import ArticulationCfg  # 關節機器人配置：有輪子、關節的機器人
from isaaclab.utils.assets import ISAAC_NUCLEUS_DIR  # NVIDIA 資源庫路徑：預設機器人模型存放處

# ============================================================================
# Charge 機器人配置
# ============================================================================
# 這個配置定義了 Charge 機器人的：
# 1. 物理模型（3D 外觀、質量、碰撞體）
# 2. 初始狀態（出生位置、姿態）
# 3. 執行器（輪子如何驅動）
# 
# 機器人類型：差速驅動（兩個主輪獨立控制，前方有兩個輔助萬向輪）
# ============================================================================

CHARGE_CFG = ArticulationCfg(
    # ------------------------------------------------------------------------
    # spawn: 機器人生成配置
    # ------------------------------------------------------------------------
    # 定義如何在模擬世界中創建這個機器人
    spawn=sim_utils.UsdFileCfg(
        # Charge 機器人 - 差速驅動底盤（兩輪獨立控制，前方有輔助萬向輪）
        usd_path="/home/aa/usd/charge/charge.usd",
        # USD 文件路徑：Charge 機器人的 3D 模型
        activate_contact_sensors=True,
        # 接觸傳感器：True = 啟用（用於檢測機器人與障礙物的真實碰撞）
        # --------------------------------------------------------------------
        # rigid_props: 剛體物理屬性
        # --------------------------------------------------------------------
        # 定義機器人如何受物理規則影響
        rigid_props=sim_utils.RigidBodyPropertiesCfg(
            disable_gravity=False,
            # 重力開關：False = 機器人會掉到地上（正常）
            #          True = 機器人會漂浮（用於飛行器）
            max_depenetration_velocity=1.0,
            # 穿模修正速度：當機器人卡進障礙物時，物理引擎會以最大 1.0 m/s 的速度把它推出來
            # 太大會導致機器人「彈飛」，太小會卡住
        ),
        
        # --------------------------------------------------------------------
        # articulation_props: 關節物理屬性
        # --------------------------------------------------------------------
        # 定義機器人的關節（輪子、手臂）如何計算
        articulation_props=sim_utils.ArticulationRootPropertiesCfg(
            enabled_self_collisions=False,
            # 自碰撞檢測：False = 機器人自己的部件不會互相碰撞（輪子不會撞車身）
            #            True = 會檢測（用於複雜機械手，防止手指打架）
            
            solver_position_iteration_count=4,
            # 位置求解器迭代次數：物理引擎計算關節位置的精度
            # 4 = 標準精度（夠用且快）
            # 越高越精確但越慢（機械手可能用 8-16）
            
            solver_velocity_iteration_count=1,
            # 速度求解器迭代次數：物理引擎計算關節速度的精度
            # 1 = 輪式機器人夠用（速度控制簡單）
            # 高速碰撞場景可能需要 4
        ),
    ),
    
    # ------------------------------------------------------------------------
    # init_state: 初始狀態
    # ------------------------------------------------------------------------
    # 定義機器人剛生成時的位置和姿態
    init_state=ArticulationCfg.InitialStateCfg(
        pos=(0.0, 0.0, 0.0),  # 初始位置 (X, Y, Z) = 世界原點，貼地
        # X: 東西方向, Y: 南北方向, Z: 高度
        # (0, 0, 0) 表示機器人底盤貼在地面上
        
        joint_pos={
            ".*": 0.0,  # 所有關節初始角度 = 0 度/弧度
            # ".*" 是正則表達式，匹配所有關節名稱
            # 例如："left_wheel", "right_wheel" 都會設為 0
        },
        
        joint_vel={
            ".*": 0.0,  # 所有關節初始速度 = 0（靜止狀態）
        },
    ),
    
    # ------------------------------------------------------------------------
    # actuators: 執行器配置
    # ------------------------------------------------------------------------
    # 定義如何驅動機器人的輪子（馬達控制方式）
    actuators={
        # ✅ 改為速度控制（適合輪式機器人）
        "wheels": ImplicitActuatorCfg(
            # "wheels" 是這個執行器的名稱（自定義，方便引用）
            
            joint_names_expr=["right_wheel_joint", "left_wheel_joint"],
            # 明確指定兩個主驅動輪的關節名稱
            # right_wheel_joint：右輪關節
            # left_wheel_joint：左輪關節
            # 注意：前方的輔助萬向輪不需要控制（被動輪）
            
            stiffness=0.0,  # 位置控制剛度：0 = 不用位置控制（純速度控制）
            # stiffness > 0: 關節會試圖達到目標角度（用於機械手）
            # stiffness = 0: 只控制速度（用於輪子）
            
            damping=10.0,  # 阻尼係數：模擬馬達的速度控制特性
            # 越高 = 響應越慢但越穩定（像黏滯液體）
            # 10.0 = 適中的響應速度（0.1秒內達到目標速度）
            
            velocity_limit=100.0,  # 最大角速度限制：100 rad/s
            # 100 rad/s ≈ 955 RPM（很高，實際會被動作限制約束）
            # 實際最大速度由 charge_env_cfg.py 中的 max_linear_velocity 控制
        ),
    },
)