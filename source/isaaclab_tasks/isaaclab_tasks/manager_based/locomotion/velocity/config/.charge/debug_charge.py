# ============================================================================
# 文件說明
# ============================================================================
"""
Charge 診斷腳本

這個腳本用於檢查 Charge 機器人環境是否正確配置和運作。

功能：
1. 顯示機器人基本信息（關節、Body、執行器）
2. 顯示動作配置信息
3. 執行手動控制測試（發送動作，觀察機器人移動）
4. 診斷常見問題（機器人不動、配置錯誤等）

使用場景：
- 首次設置環境時驗證配置
- 修改配置後檢查是否正確
- 調試機器人不動的問題
- 理解機器人的結構和參數

使用方法：
    python charge/debug_charge.py --num_envs 4
    python charge/debug_charge.py --num_envs 1 --headless  # 無頭模式（不顯示視窗）
"""

# ============================================================================
# 模塊導入
# ============================================================================
import argparse  # 命令行參數解析
import torch  # PyTorch：用於張量運算和設備管理

# Isaac Lab 應用啟動器
from isaaclab.app import AppLauncher
# AppLauncher：負責啟動 Isaac Sim 應用程序
# 必須在導入其他 Isaac Lab 模塊之前啟動

# ============================================================================
# 命令行參數解析
# ============================================================================
# 解析用戶輸入的命令行參數
parser = argparse.ArgumentParser(
    description="Charge 機器人診斷腳本"
    # 創建參數解析器（用於處理命令行參數）
)

parser.add_argument("--num_envs", type=int, default=4)
# 添加自定義參數：並行環境數量
# --num_envs 4：同時運行 4 個環境（用於測試）
# 默認值：4（較少，方便觀察）
# 訓練時通常用 128 或更多

AppLauncher.add_app_launcher_args(parser)
# 添加 Isaac Sim 的啟動參數
# 這會自動添加以下參數：
#   --headless：無頭模式（不顯示視窗，用於服務器）
#   --device：計算設備（cuda:0, cpu）
#   --num_envs：環境數量（會被上面的參數覆蓋）
#   等等...

args_cli = parser.parse_args()
# 解析命令行參數
# 例如：python debug_charge.py --num_envs 2 --headless
#       → args_cli.num_envs = 2, args_cli.headless = True

# ============================================================================
# 啟動 Isaac Sim 應用程序
# ============================================================================
# 這一步必須在導入其他 Isaac Lab 模塊之前執行！
# 因為 Isaac Sim 需要先初始化才能使用

app_launcher = AppLauncher(args_cli)
# 創建應用啟動器（使用命令行參數）
# 這會啟動 Isaac Sim 應用程序（3D 模擬器）

simulation_app = app_launcher.app
# 獲取應用程序實例
# 用於後續關閉應用程序（simulation_app.close()）

# ============================================================================
# 導入環境相關模塊（必須在 AppLauncher 之後）
# ============================================================================
# 為什麼要在 AppLauncher 之後導入？
# - Isaac Lab 的模塊依賴 Isaac Sim 的初始化
# - 如果提前導入會導致錯誤（模塊找不到）

import gymnasium as gym
# Gymnasium：強化學習環境標準接口
# 提供統一的環境接口（reset、step、close 等）

from isaaclab_tasks.utils.parse_cfg import parse_env_cfg
# 環境配置解析器
# 用於從註冊的環境名稱創建配置對象

# ============================================================================
# 創建環境配置
# ============================================================================
# ✅ 修復：正確創建環境配置
env_cfg = parse_env_cfg(
    "Isaac-Navigation-Charge-v0",  # 環境名稱（必須在環境註冊表中）
    # 這個名稱對應到 charge_env_cfg.py 中定義的環境
    # 需要在 __init__.py 或環境註冊表中註冊
    
    device=args_cli.device,  # 計算設備（cuda:0 或 cpu）
    # args_cli.device 來自 AppLauncher 的參數
    # 如果沒有指定，會自動選擇（有 GPU 就用 GPU）
    
    num_envs=args_cli.num_envs,  # 並行環境數量
    # 從命令行參數獲取（默認 4）
)

# ============================================================================
# 創建環境實例
# ============================================================================
env = gym.make("Isaac-Navigation-Charge-v0", cfg=env_cfg)
# 使用 Gymnasium 接口創建環境
# 
# gym.make()：工廠函數，根據名稱創建環境
# "Isaac-Navigation-Charge-v0"：環境名稱（必須已註冊）
# cfg=env_cfg：使用上面創建的配置
# 
# 返回的 env 是 ManagerBasedRLEnv 的實例
# 提供標準的 Gymnasium 接口：
#   - reset()：重置環境
#   - step(action)：執行動作
#   - close()：關閉環境

# ============================================================================
# 診斷報告開始
# ============================================================================
print("\n" + "="*70)
# 打印分隔線（70 個等號）
# "\n" 表示換行（空一行）

print("🔍 Charge 診斷報告")
# 診斷報告標題

print("="*70)
# 打印分隔線

# ============================================================================
# 1. 機器人信息
# ============================================================================
# 檢查機器人的基本結構（關節、Body、執行器）

robot = env.unwrapped.scene["robot"]
# 獲取機器人資產
# env.unwrapped：獲取底層環境（繞過 Gymnasium 包裝）
# scene["robot"]：從場景中獲取名為 "robot" 的資產
# 
# robot 是 Articulation 類的實例（關節機器人）

print(f"\n【機器人信息】")
# 打印區塊標題

print(f"  關節數量: {robot.num_joints}")
# 關節數量：機器人有多少個可動關節
# 例如：Charge 有 4 個關節（4 個輪子）

print(f"  關節名稱: {robot.joint_names}")
# 關節名稱列表：每個關節的名稱
# 例如：['front_left_wheel_joint', 'front_right_wheel_joint', ...]
# 
# 這很重要！用於：
# - 確認關節名稱是否正確
# - 檢查正則表達式匹配是否正確（charge_cfg.py 中的 ".*wheel.*"）

print(f"  Body數量: {robot.num_bodies}")
# Body 數量：機器人有多少個剛體（零件）
# 例如：Charge 有 8 個 Body（底盤 + 4 個輪子 + 其他零件）

print(f"  Body名稱: {robot.body_names}")
# Body 名稱列表：每個 Body 的名稱
# 例如：['chassis_link', 'front_left_wheel_link', ...]
# 
# Link 和 Body 的區別：
# - Link：機器人的「零件」（有質量、形狀）
# - Joint：連接零件的「軸」（可動關節）

# ============================================================================
# 2. 動作信息
# ============================================================================
# 檢查動作空間的配置（動作維度、動作項等）

print(f"\n【動作配置】")
# 打印區塊標題

print(f"  動作空間: {env.action_space}")
# 動作空間：Gymnasium 的動作空間對象
# 例如：Box(-1.0, 1.0, (2,), float32)
#       表示：2 維動作，範圍 [-1, 1]
# 
# 這對應到神經網絡的輸出維度

print(f"  動作維度: {env.unwrapped.action_manager.total_action_dim}")
# 總動作維度：所有動作項的維度總和
# 例如：2（前進速度 + 旋轉速度）
# 
# action_manager：動作管理器（管理所有動作項）
# total_action_dim：總維度（所有動作項的維度相加）

print(f"  動作項數量: {len(env.unwrapped.action_manager._terms)}")
# 動作項數量：有多少個動作項
# 例如：1（只有一個差速驅動動作項）
# 
# _terms：動作項字典（名稱 → 動作項對象）

# ------------------------------------------------------------------------
# 遍歷每個動作項，顯示詳細信息
# ------------------------------------------------------------------------
for name, term in env.unwrapped.action_manager._terms.items():
    # 遍歷所有動作項
    # name：動作項名稱（例如："diff_drive"）
    # term：動作項對象（例如：DifferentialDriveAction 實例）
    
    print(f"\n  動作項 '{name}':")
    # 打印動作項名稱
    
    print(f"    類型: {type(term).__name__}")
    # 動作項類型：類的名稱
    # 例如："DifferentialDriveAction"
    # 
    # 這用於確認動作項是否正確創建
    
    print(f"    維度: {term.action_dim}")
    # 動作維度：這個動作項的維度
    # 例如：2（前進速度 + 旋轉速度）
    
    # --------------------------------------------------------------------
    # 嘗試獲取更多信息（如果有的話）
    # --------------------------------------------------------------------
    if hasattr(term, '_asset'):
        # 檢查動作項是否有 _asset 屬性（控制的資產）
        print(f"    控制資產: {term._asset.cfg.prim_path}")
        # 打印控制的資產路徑
        # 例如："/World/envs/env_0/Robot"
    
    if hasattr(term, 'cfg'):
        # 檢查動作項是否有配置對象
        cfg = term.cfg
        if hasattr(cfg, 'joint_names'):
            # 檢查配置是否有關節名稱（某些動作項會直接控制關節）
            print(f"    目標關節模式: {cfg.joint_names}")
            # 打印關節名稱模式（正則表達式）
            # 例如：[".*wheel.*"]

# ============================================================================
# 3. 執行器信息
# ============================================================================
# 檢查執行器配置（馬達控制參數）

print(f"\n【執行器配置】")
# 打印區塊標題

for name, actuator in robot.actuators.items():
    # 遍歷所有執行器
    # name：執行器名稱（例如："wheels"）
    # actuator：執行器對象（例如：ImplicitActuator 實例）
    
    print(f"  '{name}':")
    # 打印執行器名稱
    
    print(f"    關節: {actuator.joint_names}")
    # 控制的關節列表：這個執行器控制哪些關節
    # 例如：['front_left_wheel_joint', 'front_right_wheel_joint', ...]
    # 
    # 這用於確認正則表達式匹配是否正確
    
    print(f"    數量: {len(actuator.joint_names)}")
    # 關節數量：這個執行器控制多少個關節
    # 例如：4（4 個輪子）
    
    print(f"    剛度: {actuator.stiffness}")
    # 剛度係數：位置控制的剛度
    # 例如：0.0（速度控制，不關心位置）
    # 
    # stiffness > 0：位置控制（機械手用）
    # stiffness = 0：速度控制（輪子用）
    
    print(f"    阻尼: {actuator.damping}")
    # 阻尼係數：速度控制的阻尼
    # 例如：10.0（適中的響應速度）
    # 
    # 阻尼越高，響應越慢但越穩定

# ============================================================================
# 4. 手動控制測試
# ============================================================================
# 發送動作給機器人，觀察是否正常移動
# 這是診斷的核心測試！

print(f"\n【手動控制測試】")
# 打印區塊標題

obs, _ = env.reset()
# 重置環境
# obs：初始觀測（shape: [num_envs, obs_dim]）
# _：info 字典（這裡忽略）
# 
# 重置後：
# - 機器人會出現在隨機位置
# - 目標位置會重新生成
# - 所有狀態會初始化

# ------------------------------------------------------------------------
# 創建最大動作（測試用）
# ------------------------------------------------------------------------
max_action = torch.ones(
    args_cli.num_envs,  # 環境數量
    env.action_space.shape[0],  # 動作維度（例如：2）
    device=env.unwrapped.device  # 設備（GPU 或 CPU）
) * 5.0
# 創建一個「極大」的動作
# shape: [num_envs, 2]
# 值：5.0（遠超過 [-1, 1] 的範圍）
# 
# 為什麼用 5.0？
# - 測試動作是否會被正確限制
# - 如果機器人動了，說明動作系統正常
# - 如果機器人沒動，可能是動作處理有問題

print(f"  發送動作: shape={max_action.shape}, 值={max_action[0]}")
# 打印動作信息
# 例如：shape=torch.Size([4, 2]), 值=tensor([5., 5.])
# 
# 這用於確認動作格式是否正確

print(f"\n  執行 10 步...")
# 提示開始執行測試

initial_pos = robot.data.root_pos_w[0, :2].clone()
# 記錄初始位置（只記錄第一個環境）
# root_pos_w：機器人根部在世界座標系的位置
# [0, :2]：第一個環境，只要 XY（忽略 Z 高度）
# clone()：創建副本（避免後續修改影響）
# 
# shape: [2] = [X, Y]

# ------------------------------------------------------------------------
# 執行 10 步測試
# ------------------------------------------------------------------------
for i in range(10):
    # 循環執行 10 步
    
    obs, reward, terminated, truncated, info = env.step(max_action.cpu().numpy())
    # 執行一步
    # 
    # 參數：
    #   max_action.cpu().numpy()：將 PyTorch 張量轉換為 NumPy 數組
    #                             Gymnasium 接口需要 NumPy
    # 
    # 返回值：
    #   obs：觀測（shape: [num_envs, obs_dim]）
    #   reward：獎勵（shape: [num_envs]）
    #   terminated：是否終止（shape: [num_envs]）
    #   truncated：是否截斷（shape: [num_envs]）
    #   info：額外信息（字典）
    
    # --------------------------------------------------------------------
    # 每 3 步打印一次狀態（避免輸出太多）
    # --------------------------------------------------------------------
    if i % 3 == 0:  # 第 0、3、6、9 步
        print(f"\n  Step {i}:")
        # 打印步驟編號
        
        print(f"    關節位置: {robot.data.joint_pos[0, :4]}")
        # 關節位置：前 4 個關節的角度
        # joint_pos：所有關節的位置（角度）
        # [0, :4]：第一個環境，前 4 個關節
        # 
        # 例如：tensor([0.123, -0.456, 0.789, -0.234])
        #       表示 4 個輪子的旋轉角度
        
        print(f"    關節速度: {robot.data.joint_vel[0, :4]}")
        # 關節速度：前 4 個關節的角速度
        # joint_vel：所有關節的速度（角速度）
        # [0, :4]：第一個環境，前 4 個關節
        # 
        # 例如：tensor([1.5, -1.5, 1.5, -1.5])
        #       表示 4 個輪子的旋轉速度（rad/s）
        # 
        # 如果速度為 0，說明動作沒有正確應用！
        
        print(f"    根部線速度: {robot.data.root_lin_vel_w[0]}")
        # 根部線速度：機器人整體的平移速度
        # root_lin_vel_w：根部在世界座標系的線速度
        # [0]：第一個環境
        # 
        # shape: [3] = [vx, vy, vz]
        # 例如：tensor([1.2, 0.3, 0.0])
        #       表示往東 1.2 m/s，往北 0.3 m/s
        
        print(f"    根部角速度: {robot.data.root_ang_vel_w[0]}")
        # 根部角速度：機器人整體的旋轉速度
        # root_ang_vel_w：根部在世界座標系的角速度
        # [0]：第一個環境
        # 
        # shape: [3] = [wx, wy, wz]
        # 例如：tensor([0.0, 0.0, 0.5])
        #       表示繞 Z 軸旋轉 0.5 rad/s（左轉）
        
        current_pos = robot.data.root_pos_w[0, :2]
        # 當前位置：機器人當前的 XY 座標
        # [0, :2]：第一個環境，只要 XY
        
        print(f"    機器人位置XY: {current_pos}")
        # 打印當前位置
        # 例如：tensor([2.5, 1.3])
        #       表示機器人在 (2.5, 1.3) 位置
        
        print(f"    移動距離: {torch.norm(current_pos - initial_pos).item():.4f}m")
        # 計算移動距離：從初始位置到當前位置的距離
        # torch.norm()：計算向量的長度（歐幾里得距離）
        # .item()：將單元素張量轉換為 Python 數值
        # :.4f：格式化為 4 位小數
        # 
        # 例如：3.4567 米
        # 
        # 如果距離很小（< 0.01 米），說明機器人幾乎沒動！

# ============================================================================
# 診斷結果總結
# ============================================================================
final_pos = robot.data.root_pos_w[0, :2]
# 最終位置：測試結束後的機器人位置

total_distance = torch.norm(final_pos - initial_pos).item()
# 總移動距離：從初始位置到最終位置的距離

print("\n" + "="*70)
# 打印分隔線

print(f"✅ 診斷完成")
# 診斷完成提示

print(f"   總移動距離: {total_distance:.4f}m")
# 打印總移動距離
# 例如：5.2341 米

# ------------------------------------------------------------------------
# 診斷結果判斷
# ------------------------------------------------------------------------
if total_distance < 0.01:
    # 如果移動距離 < 0.01 米（幾乎沒動）
    print("   ⚠️  機器人幾乎沒有移動！")
    # 警告：機器人沒有移動
    # 
    # 可能的原因：
    # 1. 動作沒有正確應用（動作處理有問題）
    # 2. 執行器配置錯誤（stiffness/damping 設置不當）
    # 3. 物理引擎問題（摩擦力太大、質量太大）
    # 4. 動作被限制（velocity_limit 太小）
    # 
    # 解決方法：
    # - 檢查 charge_cfg.py 中的執行器配置
    # - 檢查 charge_mdp.py 中的動作處理邏輯
    # - 檢查動作是否被正確縮放
else:
    print("   ✅ 機器人正常移動")
    # 成功：機器人正常移動
    # 說明動作系統工作正常！

print("="*70 + "\n")
# 打印分隔線和空行

# ============================================================================
# 清理資源
# ============================================================================
# 關閉環境和應用程序，釋放資源

env.close()
# 關閉環境
# 這會：
# - 停止物理模擬
# - 釋放 GPU 記憶體
# - 清理場景資源

simulation_app.close()
# 關閉 Isaac Sim 應用程序
# 這會：
# - 關閉 3D 視窗（如果有）
# - 釋放所有 Isaac Sim 資源
# - 結束應用程序進程

# ============================================================================
# 診斷腳本結束
# ============================================================================
# 
# 使用建議：
# 1. 首次設置環境時運行此腳本，確認配置正確
# 2. 修改配置後運行此腳本，檢查是否破壞了功能
# 3. 機器人不動時運行此腳本，找出問題所在
# 4. 理解機器人結構時查看輸出信息
# 
# 常見問題診斷：
# - 關節數量為 0：USD 文件路徑錯誤或文件不存在
# - 動作維度不匹配：動作配置錯誤
# - 機器人不動：執行器配置或動作處理有問題
# - 關節名稱不匹配：正則表達式匹配失敗
